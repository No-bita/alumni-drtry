function key(raw: string): string {
  return raw.trim().replace(/\s+/g, " ").toLowerCase();
}

const BY_KEY = new Map<string, string>([
  ...COUNTRY_NAMES.map((n) => [key(n), n] as [string, string]),
  ...Object.entries(COUNTRY_ALIASES).map(([k, n]) => [key(k), n] as [string, string])
]);

/** "usa" → "United States"; an unknown country comes back as typed (spaces tidied). Empty → "". */
export function normalizeCountry(raw: string | null | undefined): string {
  const tidy = (raw ?? "").trim().replace(/\s+/g, " ");
  if (!tidy) return "";
  return BY_KEY.get(key(tidy)) ?? tidy;
}

/** True when the country is one of COUNTRY_NAMES (after normalising). */
export function isKnownCountry(raw: string | null | undefined): boolean {
  const name = normalizeCountry(raw);
  return Boolean(name) && COUNTRY_NAMES.includes(name);
}

/**
 * Every lowercase spelling that means the same country as `raw`, for matching stored rows
 * (older rows may say "USA" where new ones say "United States").
 */
export function countryMatchKeys(raw: string | null | undefined): string[] {
  const name = normalizeCountry(raw);
  if (!name) return [];
  const keys = new Set<string>([key(name), key(raw ?? "")]);
  for (const [k, n] of Object.entries(COUNTRY_ALIASES)) if (n === name) keys.add(key(k));
  keys.delete("");
  return [...keys];
}
